import fs from 'node:fs';
import assert from 'node:assert/strict';
const source=fs.readFileSync('frontend/bridge.js','utf8').replace('/* APP */','root.testFetch=fetch;');
const render=(await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'))).default;
const root={}, sent=[], bootstrap={latest:'2026Q3'}, send=(name,request)=>sent.push({name,request});
render({parentElement:root,data:{bootstrap},setTriggerValue:send});
const controller=root.__pusula;
assert.equal(await (await root.testFetch('/api/bootstrap')).json(),bootstrap);
const first=root.testFetch('/api/catalog'), second=root.testFetch('/api/data?period=2025Q3&refresh=1');
assert.equal(sent.length,1,'Concurrent requests must be serialized');
render({parentElement:root,data:{reply:{id:sent[0].request.id,ok:true,body:{periods:[1]}}},setTriggerValue:send});
assert.equal(root.__pusula,controller,'Rerun must preserve controller and UI state');
assert.equal(sent.length,2);
assert.deepEqual(await (await first).json(),{periods:[1]});
assert.equal(sent[1].request.period,'2025Q3');assert.equal(sent[1].request.refresh,true);
render({parentElement:root,data:{reply:{id:sent[0].request.id,ok:true,body:{}}},setTriggerValue:send});
assert.ok(controller.active,'Duplicate reply must not consume another request');
render({parentElement:root,data:{reply:{id:sent[1].request.id,ok:false,body:{error:'TSB unavailable'}}},setTriggerValue:send});
const response=await second;assert.equal(response.ok,false);assert.equal((await response.json()).error,'TSB unavailable');
assert.equal(controller.active,null);assert.equal(controller.queue.length,0);
console.log('PASS: Streamlit rerun state, serialized requests, refresh flag, duplicate replies and errors.');
